// Helper to generate a realistic 50-day historical price series
// ensuring that the 50-day simple moving average approximates `ma50`
// and ends at `currentPrice`.
function generatePriceHistory(currentPrice: number, ma50: number, volatility = 0.015): number[] {
  const points: number[] = [];
  // Target sum for the 50 days to equal ma50 * 50
  const targetSum = ma50 * 50;
  
  // Create a base drift curve from an initial price to currentPrice
  // Start from an anchor roughly such that average balances around ma50
  const startPrice = 2 * ma50 - currentPrice;
  let current = startPrice;

  for (let i = 0; i < 49; i++) {
    const progress = i / 49;
    // trend towards currentPrice with small deterministic pseudo-random walk
    const trend = startPrice + (currentPrice - startPrice) * progress;
    const wave = Math.sin(i * 0.45) * (currentPrice * volatility);
    const noise = Math.cos(i * 0.9) * (currentPrice * volatility * 0.5);
    const val = Number((trend + wave + noise).toFixed(2));
    points.push(Math.max(val, currentPrice * 0.5));
  }
  points.push(currentPrice);

  // Normalize slightly so the mean closely reflects ma50
  const currentSum = points.reduce((acc, p) => acc + p, 0);
  const diffPerPoint = (targetSum - currentSum) / 50;
  
  return points.map((p, idx) => {
    if (idx === 49) return currentPrice; // keep final price exact
    return Number(Math.max(p + diffPerPoint, currentPrice * 0.4).toFixed(2));
  });
}

function generateVolumeHistory(weeklyAvg: number, currentVol: number): number[] {
  return [
    Math.round(weeklyAvg * 0.92),
    Math.round(weeklyAvg * 1.04),
    Math.round(weeklyAvg * 0.98),
    Math.round(weeklyAvg * 1.02),
    currentVol,
  ];
}

